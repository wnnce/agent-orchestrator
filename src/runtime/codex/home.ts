import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import type { CodexConfig } from "../../config/service.ts";
import type { McpServerConfig, ProjectConfig } from "../../domain/types.ts";
import { SkillManager } from "../../project/skills.ts";

/** Keys of `runtimes.codex` that configure the orchestrator rather than Codex itself. */
const SERVICE_ONLY_KEYS = new Set(["apiKey", "baseConfigPath", "mcpServers", "config"]);

/**
 * Prepares CODEX_HOME for a project: the service API key in auth.json (replacing any imported
 * login), project skills, and a generated config.toml.
 */
export async function prepareCodexHome(options: {
  codexHome: string;
  project: ProjectConfig;
  serviceConfig: CodexConfig;
  inheritedSkillsProject?: ProjectConfig | undefined;
}): Promise<void> {
  const { codexHome, project, serviceConfig } = options;
  const apiKey = serviceConfig.apiKey?.trim();
  if (!apiKey) throw new Error("runtimes.codex.apiKey must be configured in the service YAML");

  await mkdir(codexHome, { recursive: true, mode: 0o700 });
  await writeFile(
    path.join(codexHome, "auth.json"),
    JSON.stringify({ auth_mode: "apikey", OPENAI_API_KEY: apiKey }, null, 2),
    { mode: 0o600 },
  );
  const config = await buildCodexConfig(project, serviceConfig);
  await writeFile(
    path.join(codexHome, "config.toml"),
    `# Generated by agent-orchestrator\n${stringifyToml(config)}\n`,
    { mode: 0o600 },
  );
  await SkillManager.linkSkills(codexHome, project, options.inheritedSkillsProject);
}

/**
 * Builds config.toml content. Later sources win:
 * 1. the TOML file at `baseConfigPath` (project, else service);
 * 2. `runtimes.codex` in the service YAML — every key except the orchestrator's own;
 * 3. `runtimes.codex.config`, then the project's `runtime.config`;
 * 4. the project's mapped fields: model, reasoningEffort, approvalPolicy, sandbox, MCP servers.
 * Other project runtime fields (timeouts, other runtimes' settings) never reach Codex.
 */
export async function buildCodexConfig(
  project: ProjectConfig,
  serviceConfig: CodexConfig,
): Promise<Record<string, unknown>> {
  const runtime = project.runtime;
  const baseConfigPath = runtime?.baseConfigPath ?? serviceConfig.baseConfigPath;
  let config: Record<string, unknown> = baseConfigPath
    ? parseToml(await readFile(path.resolve(baseConfigPath), "utf8"), baseConfigPath)
    : {};

  const serviceSettings = Object.fromEntries(
    Object.entries(serviceConfig).filter(([key]) => !SERVICE_ONLY_KEYS.has(key)),
  );
  config = deepMerge(config, serviceSettings);
  config = deepMerge(config, serviceConfig.config ?? {});
  config = deepMerge(config, runtime?.config ?? {});

  if (runtime?.model) config.model = runtime.model;
  if (runtime?.reasoningEffort) config.model_reasoning_effort = runtime.reasoningEffort;
  config.cli_auth_credentials_store = "file";
  config.approval_policy = runtime?.approvalPolicy ?? config.approval_policy ?? "never";
  config.sandbox_mode = runtime?.sandbox ?? config.sandbox_mode ?? "danger-full-access";

  const servers = [
    ...((serviceConfig.mcpServers ?? []) as McpServerConfig[]),
    ...(runtime?.mcpServers ?? []),
  ];
  if (servers.length > 0) {
    config.mcp_servers = {
      ...((config.mcp_servers ?? {}) as Record<string, unknown>),
      ...Object.fromEntries(servers.map((server) => [server.name, mcpServerEntry(server)])),
    };
  }
  return config;
}

function mcpServerEntry(server: McpServerConfig): Record<string, unknown> {
  const entry: Record<string, unknown> = {};
  if (server.url) entry.url = server.url;
  if (server.command) {
    entry.command = server.command;
    if (server.args) entry.args = server.args;
  }
  if (server.auth) entry.auth = server.auth;
  const headers = server.http_headers ?? server.headers;
  if (headers && Object.keys(headers).length > 0) entry.http_headers = headers;
  if (server.required !== undefined) entry.required = server.required;
  if (server.startupTimeoutSec !== undefined) entry.startup_timeout_sec = server.startupTimeoutSec;
  if (server.toolTimeoutSec !== undefined) entry.tool_timeout_sec = server.toolTimeoutSec;
  if (server.enabledTools) entry.enabled_tools = server.enabledTools;
  if (server.disabledTools) entry.disabled_tools = server.disabledTools;
  if (server.approvalMode) entry.default_tools_approval_mode = server.approvalMode;
  return entry;
}

/** Deep-merges plain objects; values from `source` win, arrays are replaced. */
export function deepMerge(
  target: Record<string, unknown>,
  source: Record<string, unknown>,
): Record<string, unknown> {
  const result: Record<string, unknown> = { ...target };
  for (const [key, value] of Object.entries(source)) {
    const current = result[key];
    result[key] =
      isPlainObject(value) && isPlainObject(current) ? deepMerge(current, value) : value;
  }
  return result;
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

// Bun's TOML support is not fully covered by @types/bun.
const toml = (
  Bun as unknown as { TOML: { parse(text: string): unknown; stringify(data: unknown): string } }
).TOML;

function parseToml(text: string, source: string): Record<string, unknown> {
  try {
    return (toml.parse(text) ?? {}) as Record<string, unknown>;
  } catch (error) {
    throw new Error(`invalid Codex base config ${source}: ${(error as Error).message}`);
  }
}

/** TOML has no null, so null and undefined values are dropped before serializing. */
function stringifyToml(data: Record<string, unknown>): string {
  return toml.stringify(withoutNulls(data));
}

function withoutNulls(value: unknown): unknown {
  if (Array.isArray(value)) return value.filter((item) => item != null).map(withoutNulls);
  if (isPlainObject(value)) {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([, item]) => item != null)
        .map(([key, item]) => [key, withoutNulls(item)]),
    );
  }
  return value;
}
